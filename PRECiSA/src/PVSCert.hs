-- | @PRECiSA@relative_error@ is where 'relative_error_bound' lives, and the
--   bridge lemmas emitted by 'printCerts' are the only things that cite it.
--
--   It is therefore imported ONLY under @--relative-error@, and never from
--   @PRECiSA@strategies@: that theory is in the import chain of every
--   certificate PRECiSA has ever generated, so importing an UNVERIFIED theory
--   from it would drag it -- and its unproved TCC -- into the proof context of
--   users who never asked for a relative bound.
--
--   With the flag off this is 'emptyDoc', and @empty $$ d == d@, so the
--   generated text is byte-identical to what it was before the feature.
--
--   The NUMERIC certificate needs no import of its own: it does
--   @IMPORTING <name>_cert@ and so inherits this one transitively.
importRelErrTheory :: Bool -> Doc
importRelErrTheory True  = text "IMPORTING PRECiSA@relative_error"
importRelErrTheory False = emptyDoc

